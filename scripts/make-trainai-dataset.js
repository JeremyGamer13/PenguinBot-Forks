const fs = require("fs");
const path = require("path");

const Ollama = require("ollama-chatting");
const OllamaChat = new Ollama({ host: "http://localhost:11434" });

const databaseResult = require("../databases/train-ai.json");

// arg
const scriptArguments = process.argv.slice(2);
const inferModel = scriptArguments.shift();
const percentReferToAuthor = Number(scriptArguments.shift() || NaN);
const datasetOutputPath = scriptArguments.shift();
if (!inferModel) throw new Error("Specify infer model (ex: gemma3:270m, gemma3:1b, etc. This generates questions for an answer)");
if (isNaN(percentReferToAuthor) || !isFinite(percentReferToAuthor)) throw new Error("Specify amount of questions that refer to author (ex: 0.1 will make 10% of questions be: Give me a response that someone named (x) would say)");
if (percentReferToAuthor < 0 || percentReferToAuthor > 1) throw new Error("Specify amount of questions that refer to author (ex: 0.1 will make 10% of questions be: Give me a response that someone named (x) would say)");
if (!datasetOutputPath) throw new Error("Specify dataset Output path (absolute path, to store the dataset Output, this writes to a .jsonl)");
if (!path.isAbsolute(datasetOutputPath)) throw new Error("Specify dataset Output path (absolute path, to store the dataset Output, this writes to a .jsonl)");

// config
console.log("making", datasetOutputPath, "with", percentReferToAuthor * 100, "% of questions just being stylized, and the rest generated by", inferModel);

// make the hting
const modelTrainingContent = [];
for (const key in databaseResult) {
    if (key.startsWith("a-")) continue; // we do this when parsing messages

    const messages = databaseResult[key];
    for (const message of messages) {
        const authorId = key.split("-").pop();
        const authorName = databaseResult[`a-${authorId}`];
        if (!authorName) continue;

        const messageContent = `${message.trim().replace(/\n/g, " ").replaceAll('"', "'")}`;
        if (modelTrainingContent.find(snippet => snippet.content === messageContent))
            continue;

        modelTrainingContent.push({
            username: authorName,
            content: messageContent,
        });
    }
}

// shuffle
modelTrainingContent.sort(() => Math.random() - 0.5);
console.log("done cleaning", modelTrainingContent.length, "messages");

// create the questions that are simple
const numberToCreate = Math.trunc(percentReferToAuthor * modelTrainingContent.length);
for (let i = 0; i < numberToCreate; i++) {
    const snippet = modelTrainingContent[i];
    const question = `Write a message in the exact style and manner that someone named "${snippet.username}" would speak in.`;
    snippet.question = question;
}

// shuffle & count
const numberLeftToGenerate = () => {
    return modelTrainingContent.filter(snippet => !snippet.question).length;
};
modelTrainingContent.sort(() => Math.random() - 0.5);
console.log("made", numberToCreate, "auto-questions, ", numberLeftToGenerate(), "left to generate");

// GENERATE THE REST OF THE QUESTIONS
function progressBar(progress) {
    const width = 35;
    const filled = Math.round((progress) * width);

    return `${'█'.repeat(filled) + '░'.repeat(width - filled)} (${Math.floor(progress * 10000) / 100}%)`;
}

(async () => {
    while (numberLeftToGenerate()) {
        const snippet = modelTrainingContent.find(snippet => !snippet.question);
        try {
            const response = await OllamaChat.generate({
                model: inferModel,
                think: false,
                timeout: 20 * 1000, // 20 seconds
                system: `You are a short prompt generator. You generate prompts to responses that you are given.`
                    + "\n" + "Your sole job is to output a single, direct conversational prompt that would naturally elicit the given response."
                    + "\n" + "The user will provide you a single response, and you need to generate the prompt that corresponds with the response."
                    + "\n" + "- Output only the exact prompt/question in plain-text with no additional context or introduction."
                    + "\n" + "- Never repeat the response back as the question, even if the response is unreasonably short."
                    + "\n" + "- Do not include conversational filler, introductions, reasoning, explanations, or markdown boxes."
                    + "\n" + "- You must generate a relevant prompt even if the response is an incomplete thought or basic symbol."
                    + "\n" + "- Match the tone of a casual Discord user chatting with a bot.",
                prompt: `This is the response to generate a prompt for:`
                    + "\n" + `--- START OF RESPONSE ---`
                    + "\n" + `${snippet.content}`
                    + "\n" + `--- END OF RESPONSE ---`,
            });

            const finalResponse = response.response.trim();
            if (!finalResponse) throw new Error("No question given from answer");
            snippet.question = finalResponse;

            console.log("\n");
            console.log("Q:", finalResponse);
            console.log("A:", snippet.content);
            console.log(progressBar(1 - (numberLeftToGenerate() / modelTrainingContent.length)));
        } catch (err) {
            console.warn("failed to generate a response in time, this can be caused by model warmup. retrying:", err);
        }
    }

    const jsonlFileContent = modelTrainingContent
        .map(snippet => JSON.stringify({ user: snippet.question, assistant: snippet.content }))
        .join("\n");
    console.log("writing jsonl with", modelTrainingContent.length, "messages");
    fs.writeFileSync(datasetOutputPath, jsonlFileContent, "utf8");
    console.log("done, use unsloth or other tools to use this as a dataset");

})();